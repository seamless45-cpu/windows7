/**
 * Windows 7 sound scheme.
 *
 * The clips in `public/sounds` are the real Windows 7 sounds (Startup,
 * Shutdown, Logon/Logoff, Minimize, Restore, Default Beep, Ding, Error,
 * Exclamation, Notification, Recycle, Menu Command, Critical Stop, UAC). They
 * are decoded once per session and played through Web Audio so that the
 * volume slider, mute and the "No Sounds" scheme all apply to them, and so
 * that several sounds can overlap the way they do on Windows.
 */
export const snd = { vol: 0.5, muted: false, scheme: "default" as string, keyClick: false };

export type SysSound =
  | "startup"
  | "shutdown"
  | "logon"
  | "logoff"
  | "error"
  | "exclaim"
  | "ding"
  | "balloon"
  | "default"
  | "recycle"
  | "minimize"
  | "restore"
  | "menu"
  | "critical"
  | "uac";

/** Every sound that ships with the simulator. */
export const SOUND_FILES: Record<SysSound, string> = {
  startup: "startup",
  shutdown: "shutdown",
  logon: "logon",
  logoff: "logoff",
  error: "error",
  exclaim: "exclaim",
  ding: "ding",
  balloon: "balloon",
  default: "default",
  recycle: "recycle",
  minimize: "minimize",
  restore: "restore",
  menu: "menu",
  critical: "critical",
  uac: "uac",
};

// Inlined by next.config.ts (`env`): "" locally, "/windows7" on GitHub Pages.
const BASE = process.env.NEXT_PUBLIC_BASE_PATH || "";

let ctx: AudioContext | null = null;
const buffers = new Map<SysSound, AudioBuffer | "loading" | "failed">();
const pending = new Set<SysSound>();

export function ac(): AudioContext | null {
  if (typeof window === "undefined") return null;
  if (!ctx) {
    const C = window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    if (!C) return null;
    ctx = new C();
  }
  if (ctx.state === "suspended") ctx.resume().catch(() => {});
  return ctx;
}

const url = (k: SysSound) => `${BASE}/sounds/${SOUND_FILES[k]}.mp3`;

/** Fetch and decode a sound clip; safe to call repeatedly. */
export function preload(kinds: SysSound[] = Object.keys(SOUND_FILES) as SysSound[]) {
  const c = ac();
  if (!c) return;
  kinds.forEach((k) => {
    if (buffers.has(k) || pending.has(k)) return;
    pending.add(k);
    buffers.set(k, "loading");
    fetch(url(k))
      .then((r) => (r.ok ? r.arrayBuffer() : Promise.reject(new Error(String(r.status)))))
      .then((ab) => c.decodeAudioData(ab))
      .then((buf) => buffers.set(k, buf))
      .catch(() => {
        buffers.set(k, "failed");
        pending.delete(k);
      });
  });
}

function playBuffer(buf: AudioBuffer) {
  const c = ac();
  if (!c) return;
  const src = c.createBufferSource();
  const g = c.createGain();
  src.buffer = buf;
  g.gain.value = Math.min(1, Math.max(0, snd.vol));
  src.connect(g);
  g.connect(c.destination);
  src.start();
}

/**
 * Play a Windows system sound.
 *
 * `key` is a single click for the on-screen keyboard, which Windows does not
 * have; it stays synthesised and is only heard when "keyboard click" is on.
 */
export function playSys(kind: SysSound | "key") {
  if (snd.muted || snd.vol <= 0) return;
  if (snd.scheme === "none") return;
  if (kind === "key") return; // keyboard clicks are generated by playClick
  const c = ac();
  if (!c) return;
  const buf = buffers.get(kind);
  if (typeof buf === "object") {
    playBuffer(buf);
    return;
  }
  if (buf === "failed" || buf === undefined) {
    preload([kind]);
    // nothing to play yet — a repeated call (hover, redo) will succeed once decoded
  }
}

/** Play preloaded clips without gestures, used after the first user interaction. */
export function unlockAudio() {
  const c = ac();
  if (c && c.state === "suspended") c.resume().catch(() => {});
  preload();
}

/* keep a reference so `import { tone }` in older call sites keeps working */
export function tone(freq: number, start: number, dur: number, type: OscillatorType = "sine", gain = 0.2) {
  const c = ac();
  if (!c) return;
  const o = c.createOscillator();
  const g = c.createGain();
  o.type = type;
  o.frequency.value = freq;
  const t0 = c.currentTime + start;
  g.gain.setValueAtTime(0.0001, t0);
  g.gain.exponentialRampToValueAtTime(Math.max(0.0002, gain), t0 + 0.02);
  g.gain.exponentialRampToValueAtTime(0.0001, t0 + dur);
  o.connect(g);
  g.connect(c.destination);
  o.start(t0);
  o.stop(t0 + dur + 0.05);
}

/** Very short click used for the "keyboard click" accessibility option. */
export function playClick() {
  if (!snd.keyClick || snd.muted || snd.vol <= 0) return;
  const c = ac();
  if (!c) return;
  const o = c.createOscillator();
  const g = c.createGain();
  o.type = "square";
  o.frequency.value = 1400;
  g.gain.setValueAtTime(0.02 * snd.vol, c.currentTime);
  g.gain.exponentialRampToValueAtTime(0.0001, c.currentTime + 0.02);
  o.connect(g);
  g.connect(c.destination);
  o.start();
  o.stop(c.currentTime + 0.03);
}

/** Read back the volume/mute/scheme values from settings on start-up. */
export function initSound() {
  try {
    const raw = typeof localStorage === "undefined" ? null : localStorage.getItem("win7.settings");
    const s = (raw ? JSON.parse(raw) : {}) as { volume?: number; muted?: boolean; soundScheme?: string; keyClick?: boolean };
    if (typeof s.volume === "number") snd.vol = s.volume / 100;
    if (typeof s.muted === "boolean") snd.muted = s.muted;
    if (s.soundScheme === "none" || s.soundScheme === "default") snd.scheme = s.soundScheme;
    if (typeof s.keyClick === "boolean") snd.keyClick = s.keyClick;
  } catch {
    /* no saved settings */
  }
}
